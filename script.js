  // 5. CARTA CON ESCRITURA PROGRESIVA
  // ============================================================
  let cartaIniciada = false;

  function initCartaVisible() {
    if (cartaIniciada) return;
    const zonaCarta = $("#carta");
    if (!zonaCarta) return;

    if (typeof IntersectionObserver === "undefined") {
      escribirCarta();
      return;
    }

    const observer = new IntersectionObserver(
      (entradas) => {
        entradas.forEach((entrada) => {
          if (entrada.isIntersecting) {
            escribirCarta();
            observer.disconnect();
          }
        });
      },
      { threshold: 0.35 }
    );
    observer.observe(zonaCarta);
  }

  function escribirCarta() {
    if (cartaIniciada) return;
    cartaIniciada = true;

    const elCarta = $("#carta-texto");
    const firma = $("#carta-firma");
    if (!elCarta) return;

    const texto = CONFIG.carta || "";

    if (menosMovimiento) {
      // Sin animación: muestra el texto completo de inmediato
      elCarta.innerHTML = resaltarPalabras(texto);
      if (firma) firma.classList.add("visible");
      return;
    }

    // Para cartas largas, escribe en bloques para que no tarde eternidades
    const esLarga = texto.length > 2500;
    const velocidadBase = Math.max(6, CONFIG.velocidadEscrituraCarta || 28);
    // Objetivo: cartas largas se escriben en ~50–70 s
    const velocidad = esLarga
      ? Math.max(1, Math.round((55 * 1000) / texto.length))
      : velocidadBase;
    const salto = esLarga ? Math.max(2, Math.round(texto.length / 1800)) : 1;

    elCarta.innerHTML =
      '<span class="cursor-escritura" aria-hidden="true"></span>';
    const cursor = elCarta.querySelector(".cursor-escritura");

    // Botón para saltar la animación y leer todo de una vez
    const btnSaltar = document.createElement("button");
    btnSaltar.type = "button";
    btnSaltar.className = "boton-saltar-carta";
    btnSaltar.textContent = "Leer de una vez";
    elCarta.parentElement.appendChild(btnSaltar);

    let cancelado = false;

    function terminar() {
      cancelado = true;
      elCarta.innerHTML = resaltarPalabras(texto);
      if (firma) firma.classList.add("visible");
      btnSaltar.remove();
    }

    btnSaltar.addEventListener("click", terminar);

    let i = 0;

    function paso() {
      if (cancelado) return;

      if (i >= texto.length) {
        if (cursor) cursor.remove();
        if (firma) firma.classList.add("visible");
        btnSaltar.remove();
        return;
      }

      // Inserta carácter a carácter, pero agrupa las marcas *destacadas*
      const resto = texto.slice(i);
      const matchDestacada = resto.match(/^\*([^*]+)\*/);

      if (matchDestacada) {
        const span = document.createElement("span");
        span.className = "palabra-destacada";
        span.textContent = matchDestacada[1];
        elCarta.insertBefore(span, cursor);
        i += matchDestacada[0].length;
        setTimeout(paso, velocidad * 3);
        return;
      }

      const trozo = texto.slice(i, i + salto);
      // Inserta como nodo de texto para respetar saltos de línea
      elCarta.insertBefore(document.createTextNode(trozo), cursor);
      i += salto;

      // Pausa más larga tras puntos y saltos de línea (efecto natural)
      const ultima = trozo[trozo.length - 1];
      const pausa =
        ultima === "\n" ? velocidad * (esLarga ? 3 : 8) :
        ultima === "." || ultima === "!" || ultima === "?" ? velocidad * (esLarga ? 2 : 6) :
        velocidad;

      setTimeout(paso, pausa);
    }

    paso();
  }

  function resaltarPalabras(texto) {
    const escapado = texto
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
    return escapado.replace(/\*([^*]+)\*/g, '<span class="palabra-destacada">$1</span>');
  }

